class Job(Base):
    __tablename__ = "jobs"

    # Internal id used for FK relationships ('job_' + nanoid).
    id: Mapped[str] = mapped_column(Text, primary_key=True)
    # Public-facing short id ('j_' + 12 chars) — what the frontend stores.
    hash_id: Mapped[str] = mapped_column(Text, nullable=False, unique=True)

    user_id: Mapped[str] = mapped_column(
        Text, ForeignKey("users.id"), nullable=False
    )
    tier_at_submit: Mapped[str] = mapped_column(Text, nullable=False)
    seq_no: Mapped[int] = mapped_column(Integer, nullable=False)
    set_id: Mapped[str | None] = mapped_column(Text, nullable=True)
    session_id: Mapped[str | None] = mapped_column(Text, nullable=True)

    model: Mapped[str] = mapped_column(Text, nullable=False)
    params_json: Mapped[str] = mapped_column(Text, nullable=False)
    flags_json: Mapped[str] = mapped_column(
        Text, nullable=False, server_default=text("'{}'")
    )
    client_request_id: Mapped[str | None] = mapped_column(Text, nullable=True)

    status: Mapped[str] = mapped_column(Text, nullable=False)
    status_reason: Mapped[str | None] = mapped_column(Text, nullable=True)
    provider_used: Mapped[str | None] = mapped_column(Text, nullable=True)
    retries: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=text("0")
    )
    cost_cny: Mapped[float] = mapped_column(
        nullable=False, server_default=text("0")
    )

    created_at: Mapped[datetime] = mapped_column(
        nullable=False, server_default=text("CURRENT_TIMESTAMP")
    )
    queued_at: Mapped[datetime | None] = mapped_column(nullable=True)
    dispatched_at: Mapped[datetime | None] = mapped_column(nullable=True)
    started_at: Mapped[datetime | None] = mapped_column(nullable=True)
    finished_at: Mapped[datetime | None] = mapped_column(nullable=True)
    updated_at: Mapped[datetime] = mapped_column(
        nullable=False, server_default=text("CURRENT_TIMESTAMP")
    )

    __table_args__ = (
        CheckConstraint(
            "status IN ('QUEUED','RUNNING','SUCCEEDED','FAILED','CANCELLED','DELETED')",
            name="ck_jobs_status",
        ),
        UniqueConstraint("user_id", "seq_no", name="idx_jobs_user_seq"),
        Index("idx_jobs_user_updated", "user_id", "updated_at"),
        Index("idx_jobs_user_status", "user_id", "status"),
        Index("idx_jobs_status_created", "status", "created_at"),
        Index("idx_jobs_set", "set_id"),
    )


