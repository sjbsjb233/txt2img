class Provider(Base):
    __tablename__ = "providers"

    id: Mapped[str] = mapped_column(Text, primary_key=True)
    label: Mapped[str] = mapped_column(Text, nullable=False)
    adapter_type: Mapped[str] = mapped_column(Text, nullable=False)
    base_url: Mapped[str] = mapped_column(Text, nullable=False)
    # AES-GCM encrypted; never store the cleartext key.
    api_key_enc: Mapped[str] = mapped_column(Text, nullable=False)
    cost_per_image_cny: Mapped[float] = mapped_column(nullable=False)
    initial_balance_cny: Mapped[float] = mapped_column(nullable=False)
    balance_cny: Mapped[float] = mapped_column(nullable=False)

    enabled: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=text("1")
    )
    note: Mapped[str | None] = mapped_column(Text, nullable=True)

    max_concurrency: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=text("10")
    )
    rpm_limit: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=text("600")
    )

    circuit_state: Mapped[str] = mapped_column(
        Text, nullable=False, server_default=text("'healthy'")
    )
    cooldown_until: Mapped[datetime | None] = mapped_column(nullable=True)
    # Snapshot of the in-memory metric ring buffer; refreshed periodically
    # so admin views can display recent activity without hitting the live
    # MetricsEngine.
    recent_calls_json: Mapped[str | None] = mapped_column(Text, nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        nullable=False, server_default=text("CURRENT_TIMESTAMP")
    )
    updated_at: Mapped[datetime] = mapped_column(
        nullable=False, server_default=text("CURRENT_TIMESTAMP")
    )

    __table_args__ = (
        CheckConstraint(
            "circuit_state IN ('healthy','open','half_open','drained','disabled')",
            name="ck_providers_circuit_state",
        ),
    )


