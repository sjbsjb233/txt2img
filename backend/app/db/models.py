"""SQLAlchemy ORM models — the source of truth for the SQLite schema.

Schema layout follows the design doc §14 verbatim. Field-by-field changes
must be accompanied by an alembic migration; do not edit existing
declarations here without one. New tables and indexes also belong in a new
migration revision so production data survives.

Conventions used here:
- All primary keys for entities are TEXT prefixed IDs (``u_``, ``j_``,
  ``set_``, ``img_``, ``sess_``, ``ann_``) per design doc Appendix B; they
  are generated by ``app.utils.ids`` (added in PR-08).
- Timestamps default to ``CURRENT_TIMESTAMP`` server-side. SQLite stores
  them as ISO 8601 strings; SQLAlchemy translates to Python ``datetime``.
- All TEXT columns are unicode; SQLite is encoding-agnostic but we treat
  them as UTF-8 by convention.
- ``CHECK`` constraints encode invariants the application also enforces;
  duplicating them at the DB level keeps the schema self-describing and
  catches programming errors during development.
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import (
    CheckConstraint,
    ForeignKey,
    Index,
    Integer,
    PrimaryKeyConstraint,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    """Single declarative base for every ORM model in the project."""

    pass


# ---------------------------------------------------------------------------
# Users / tiers
# ---------------------------------------------------------------------------


class User(Base):
    __tablename__ = "users"

    id: Mapped[str] = mapped_column(Text, primary_key=True)
    username: Mapped[str] = mapped_column(Text, nullable=False, unique=True)
    password_hash: Mapped[str] = mapped_column(Text, nullable=False)
    role: Mapped[str] = mapped_column(Text, nullable=False)
    tier: Mapped[str] = mapped_column(Text, nullable=False)
    status: Mapped[str] = mapped_column(
        Text, nullable=False, server_default=text("'active'")
    )
    display_name: Mapped[str | None] = mapped_column(Text, nullable=True)

    today_count: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=text("0")
    )
    today_reset_date: Mapped[str] = mapped_column(
        Text, nullable=False, server_default=text("(date('now','+8 hours'))")
    )

    override_soft_quota: Mapped[int | None] = mapped_column(Integer, nullable=True)
    override_hard_quota: Mapped[int | None] = mapped_column(Integer, nullable=True)

    last_seq_no: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default=text("0")
    )

    created_at: Mapped[datetime] = mapped_column(
        nullable=False, server_default=text("CURRENT_TIMESTAMP")
    )
    last_login_at: Mapped[datetime | None] = mapped_column(nullable=True)

    __table_args__ = (
        CheckConstraint("role IN ('admin','user')", name="ck_users_role"),
        CheckConstraint(
            "status IN ('active','disabled','deleted')", name="ck_users_status"
        ),
        Index("idx_users_status_tier", "status", "tier"),
    )


class Tier(Base):
    __tablename__ = "tiers"

    tier: Mapped[str] = mapped_column(Text, primary_key=True)
    weight: Mapped[int] = mapped_column(Integer, nullable=False)
    max_concurrency: Mapped[int] = mapped_column(Integer, nullable=False)
    max_queue: Mapped[int] = mapped_column(Integer, nullable=False)
    soft_quota: Mapped[int] = mapped_column(Integer, nullable=False)
    hard_quota: Mapped[int] = mapped_column(Integer, nullable=False)
    slo_p95_ms: Mapped[int | None] = mapped_column(Integer, nullable=True)
    updated_at: Mapped[datetime] = mapped_column(
        nullable=False, server_default=text("CURRENT_TIMESTAMP")
    )

    __table_args__ = (
        CheckConstraint(
            "tier IN ('vip','premium','standard','free')", name="ck_tiers_tier"
        ),
    )


